export function normalizeStateName(s: string): string {
  if (!s) return '';
  return s
    .toLowerCase()
    .replace(/\s*\(nct\)/gi, '')
    .replace(/\s*\(ut\)/gi, '')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

export function doesDisasterMatchState(disasterStates: string[], targetState: string): boolean {
  if (!targetState || targetState === 'all') return true;
  const normTarget = normalizeStateName(targetState);
  const targetLower = targetState.toLowerCase().trim();
  const aliases = STATE_ALIASES[targetLower] || [];

  return disasterStates.some((st) => {
    const normSt = normalizeStateName(st);
    if (normSt === normTarget) return true;
    if (normSt.length >= 3 && (normSt.includes(normTarget) || normTarget.includes(normSt))) return true;
    const stLower = st.toLowerCase().trim();
    if (aliases.some((a) => normalizeStateName(a) === normSt || stLower.includes(a) || a.includes(stLower))) return true;
    const stAliases = STATE_ALIASES[stLower] || [];
    if (stAliases.some((a) => normalizeStateName(a) === normTarget || targetLower.includes(a) || a.includes(targetLower))) return true;
    return false;
  });
}
